// Tiny Resend client. Sends an email with one or more attachments.
// If RESEND_API_KEY isn't set the caller should skip calling this function.

export interface ResendAttachment {
  filename: string;
  bytes: Uint8Array;
}

export async function sendReportEmail(opts: {
  apiKey: string;
  fromAddress: string;       // e.g. reports@esprey.net (must be on a verified domain)
  toAddress: string;
  replyTo?: string;          // optional — replies route here instead of the from-address
  monthLabel: string;
  attachments: ResendAttachment[];
}): Promise<{ id: string }> {
  const summary = opts.attachments.map((a) => `- ${a.filename}`).join("\n");
  const body: Record<string, unknown> = {
    from: `Esprey Expenses <${opts.fromAddress}>`,
    to: [opts.toAddress],
    subject: `Expense report — ${opts.monthLabel}`,
    text:
      `Your monthly expense report for ${opts.monthLabel} is attached.\n\n` +
      `Attachments:\n${summary}\n\n` +
      `Generated by Esprey Expenses.`,
    attachments: opts.attachments.map((a) => ({
      filename: a.filename,
      content: uint8ToBase64(a.bytes),
    })),
  };
  if (opts.replyTo) body.reply_to = opts.replyTo;
  const res = await fetch("https://api.resend.com/emails", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "Authorization": `Bearer ${opts.apiKey}`,
    },
    body: JSON.stringify(body),
  });
  if (!res.ok) {
    const txt = await res.text();
    throw new Error(`Resend ${res.status}: ${txt.slice(0, 500)}`);
  }
  return (await res.json()) as { id: string };
}

/** Welcome email sent to a newly-added team member, in their language. */
export async function sendWelcomeEmail(opts: {
  apiKey: string;
  fromAddress: string;
  toAddress: string;
  replyTo?: string;
  displayName?: string | null;
  addedByName?: string | null;
  appUrl: string;
  language?: "en" | "fr";
}): Promise<{ id: string }> {
  const appUrl = opts.appUrl.replace(/\/$/, "") + "/";
  const helpUrl = opts.appUrl.replace(/\/$/, "") + "/instructions";
  const fr = opts.language === "fr";
  const firstName = opts.displayName ? opts.displayName.split(" ")[0] : null;

  const body: Record<string, unknown> = {
    from: `Esprey Expenses <${opts.fromAddress}>`,
    to: [opts.toAddress],
    subject: fr ? "Vous avez été ajouté à Esprey Expenses" : "You've been added to Esprey Expenses",
    ...(opts.replyTo ? { reply_to: opts.replyTo } : {}),
    text: fr
      ? welcomeFr(firstName, opts.addedByName ?? null, appUrl, helpUrl)
      : welcomeEn(firstName, opts.addedByName ?? null, appUrl, helpUrl),
  };
  const res = await fetch("https://api.resend.com/emails", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "Authorization": `Bearer ${opts.apiKey}`,
    },
    body: JSON.stringify(body),
  });
  if (!res.ok) {
    const txt = await res.text();
    throw new Error(`Resend ${res.status}: ${txt.slice(0, 500)}`);
  }
  return (await res.json()) as { id: string };
}

function uint8ToBase64(bytes: Uint8Array): string {
  let binary = "";
  const chunk = 0x8000;
  for (let i = 0; i < bytes.length; i += chunk) {
    binary += String.fromCharCode.apply(null, bytes.subarray(i, i + chunk) as unknown as number[]);
  }
  return btoa(binary);
}


